def transform_file(file_like: io.BytesIO) -> bytes:
    df = pd.read_excel(file_like, sheet_name=0)
    df.columns = df.columns.str.strip().str.upper()

    def col(df_, *possible_names):
        for name in possible_names:
            name = name.upper()
            if name in df_.columns:
                return df_[name]
        return pd.Series([np.nan] * len(df_))

    # keep only rows which actually have data
    valid_sno = col(df, "S.NO")
    valid_sku = col(df, "ITEM NUMBER (MGD DESIGN)")
    rec = df[valid_sno.notna() & valid_sku.notna()].copy()

    mgd_sku = col(rec, "ITEM NUMBER (MGD DESIGN)").astype(str).str.strip()
    tone = col(rec, "METAL COLOR", "METALCOLOUR", "TONE")
    metal = col(rec, "METAL KARAT", "KARAT", "METALKARAT")
    qty = col(rec, "PCS", "QTY", "QUANTITY")
    size = col(rec, "SIZE3", "SIZE", "RING SIZE")
    item_po_raw = col(rec, "TARGETED SHOPS", "TARGETEDSHOPS")
    order_sl = col(rec, "ORDER SL NUMBER", "ORDER SL NO", "ORDER SL", "ORDERSLNO")
    item_ref = col(rec, "BRANCH")
    style_raw = col(rec, "SUPPLIER DESIGN NUBMER", "SUPPLIER DESIGN NUMBER", "SUPPLIERDESIGNNO")
    q_main = col(rec, "QUALITY MAIN", "CLARITY", "DIA QUALITY", "DIAMOND QUALITY", "QUALITY")
    q_shade = col(rec, "SHADE", "DMD COLOUR", "COLOUR", "COLOR")
    order_group_orig = col(rec, "REGION")
    article_desc = col(rec, "ARTICLE DESCRIPTION", "ARTICLEDESCRIPTION")

    mapped_style = mgd_sku.map(lambda k: SKU_TO_STYLE.get(str(k)))
    style = mapped_style.fillna(style_raw).astype(str).str.strip()

    # ✅ canonical region names for display (fixes 'uae' -> 'UAE', 'america' -> 'USA', etc.)
    region_display = order_group_orig.apply(canon_region)

    # stamping based on canonical region mapping above
    stamp = [stamping_for_region(r) for r in region_display]

    # build ItemPoNo with ORDER SL NUMBER prefix
    item_po_formatted = [
        _format_item_po(po, sl)
        for po, sl in zip(item_po_raw, order_sl)
    ]

    df_out = pd.DataFrame({
        "SrNo": rec["S.NO"].astype(int),
        "StyleCode": style,
        "ItemSize": size.apply(_parse_item_size).round(2),
        "OrderQty": qty.fillna(1).astype(int),
        "OrderItemPcs": 1,
        "Metal": metal.apply(_map_metal),
        "Tone": tone.apply(_map_tone),
        "ItemPoNo": item_po_formatted,
        "ItemRefNo": item_ref.astype(str).fillna("").str.strip(),
        "StockType": "",
        "MakeType": "",
        "CustomerProductionInstruction": [
            _build_customer_instruction(qm, sh, sk)
            for qm, sh, sk in zip(q_main, q_shade, mgd_sku)
        ],
        "SpecialRemarks": [
            _build_special_remarks(qm, cat)
            for qm, cat in zip(q_main, article_desc)
        ],
        "DesignProductionInstruction": "",
        "StampInstruction": stamp,
        # ✅ now uses canonical region (no lower-case 'uae')
        "OrderGroup": region_display.replace("NAN", ""),
        "Certificate": "",
        "SKUNo": mgd_sku,
        "Basestoneminwt": np.nan,
        "Basestonemaxwt": np.nan,
        "Basemetalminwt": np.nan,
        "Basemetalmaxwt": np.nan,
        "Productiondeliverydate": "",
        "Expecteddeliverydate": "",
        "SetPrice": np.nan,
        "StoneQuality": np.nan,
    })

    # ----- NEW: set grouping based on StyleCode numeric suffix within SAME ItemRefNo -----
    df_out["__style_suffix__"] = df_out["StyleCode"].map(_style_suffix)
    df_out["__set_size__"] = 1  # default

    # group by (ItemRefNo, suffix) and count how many pieces share that suffix
    for (branch, suffix), idxs in df_out.groupby(["ItemRefNo", "__style_suffix__"]).groups.items():
        idxs = list(idxs)
        if suffix == "" or len(idxs) < 2:
            continue
        # optional: require same length StyleCode
        lengths = df_out.loc[idxs, "StyleCode"].astype(str).str.len()
        if lengths.nunique() != 1:
            continue
        df_out.loc[idxs, "__set_size__"] = len(idxs)

    # append "(N PCS SET)" at the END of CustomerProductionInstruction
    mask_set = df_out["__set_size__"] > 1
    df_out.loc[mask_set, "CustomerProductionInstruction"] = (
        df_out.loc[mask_set, "CustomerProductionInstruction"].astype(str)
        + " ("
        + df_out.loc[mask_set, "__set_size__"].astype(int).astype(str)
        + " PCS SET)"
    )

    # ------------------------------------------------------------------------
    q_main_u = q_main.astype(str).str.upper().str.strip()
    df_out["__sheet__"] = np.where(q_main_u.str.startswith("SI"), "MGD-SIGH", "MGD-VVS VS GH")

    # keep article description for ordering (earring last in set)
    df_out["__article__"] = article_desc.astype(str)

    out_cols = [
        "SrNo", "StyleCode", "ItemSize", "OrderQty", "OrderItemPcs", "Metal",
        "Tone", "ItemPoNo", "ItemRefNo", "StockType", "MakeType",
        "CustomerProductionInstruction", "SpecialRemarks",
        "DesignProductionInstruction", "StampInstruction", "OrderGroup",
        "Certificate", "SKUNo", "Basestoneminwt", "Basestonemaxwt",
        "Basemetalminwt", "Basemetalmaxwt", "Productiondeliverydate",
        "Expecteddeliverydate", "SetPrice", "StoneQuality",
    ]

    output = io.BytesIO()
    with pd.ExcelWriter(output, engine="openpyxl") as writer:
        for sheet in ["MGD-VVS VS GH", "MGD-SIGH"]:
            sub = df_out[df_out["__sheet__"] == sheet].copy()
            if sub.empty:
                continue

            # sort inside sheet:
            # 1) by ItemRefNo
            # 2) by StyleCode numeric suffix (so set pieces together)
            # 3) within suffix: non-earring first, earrings last
            sub["__suffix__"] = sub["StyleCode"].map(_style_suffix)
            sub["__is_ear__"] = sub["__article__"].str.upper().str.contains("EAR")

            sub = sub.sort_values(
                ["ItemRefNo", "__suffix__", "__is_ear__", "StyleCode"],
                kind="stable"
            )

            # duplicate bangles after ordering
            sub = _expand_bangle_rows(sub).reset_index(drop=True)

            # resequence SrNo within each sheet
            sub["SrNo"] = range(1, len(sub) + 1)

            # keep only output columns
            sub = sub[out_cols]

            # text columns -> empty string instead of NaN
            text_cols = [
                "StyleCode", "Tone", "ItemPoNo", "ItemRefNo", "StockType",
                "MakeType", "CustomerProductionInstruction", "SpecialRemarks",
                "DesignProductionInstruction", "StampInstruction",
                "OrderGroup", "Certificate", "SKUNo", "StoneQuality",
            ]
            for c in text_cols:
                sub[c] = sub[c].astype(object).where(sub[c].notna(), "")

            sub.to_excel(writer, sheet_name=sheet, index=False)

    output.seek(0)
    return output.getvalue()
