def canon_region(name: str) -> str:
    if name is None or (isinstance(name, float) and np.isnan(name)):
        return ""
    s = str(name).strip().upper()
    s = " ".join(s.split())
    return REGION_ALIAS.get(s, s)

def stamping_for_region(region_name: str) -> str:
    r = canon_region(region_name)
    # direct hit first
    if r in REGION_STAMPING:
        return REGION_STAMPING[r]
    # map 'United Kingdom' -> 'UK' rule
    if r == "United Kingdom" or r == "UNITED KINGDOM":
        return REGION_STAMPING.get("UK", _DEFAULT_MLOGO)
    # fallback to default M-LOGO
    return _DEFAULT_MLOGO

def _parse_item_size(val):
    if pd.isna(val):
        return np.nan
    s = str(val)
    m = re.search(r"(\d+(?:\.\d+)?)", s)
    return float(m.group(1)) if m else np.nan

def _map_metal(val):
    if isinstance(val, str):
        v = val.strip().upper()
        if v in ("18K", "18 KT", "18KT"):
            return "GA18"
        if v in ("14K", "14 KT", "14KT"):
            return "GA14"
    return val

def _map_tone(val):
    if not isinstance(val, str):
        return val
    v = str(val).strip().upper()
    m = {"YG": "Y", "RG": "P", "WG": "W", "TWO TONE": "T", "TRI TONE": "TT"}
    return m.get(v, v[:1] if v else v)

def _stone_quality(quality_main, shade, default="VVS-VS-GH"):
    parts = []
    if isinstance(quality_main, str):
        qm = quality_main.strip().upper()
        if qm and qm != "NAN":
            parts.append(qm)
    if isinstance(shade, str):
        sh = shade.strip().upper()
        if sh and sh != "NAN":
            parts.append(sh)
    return "-".join(parts) if parts else default

def _build_customer_instruction(quality_main, shade, sku, default_scheme="VVS-VS-GH"):
    q_text = _stone_quality(quality_main, shade, default_scheme)
    return f"IGI ({q_text}) CO BRAND, PRINT MGD DESIGN CODES ({sku}) ON IGI CARD"

def _build_special_remarks(quality_main, article_desc):
    """
    Rule:
      - If Article description contains 'MANGALSUTRA'
          -> MAINTAIN GOLD & DIA WT, FISH LOCK WITH MANGALSUTRA CHAIN NEED SMALL "O"KADI
      - Elif Article description contains 'EAR'
          -> MAINTAIN GOLD & DIA WT, POST IN CENTER.
      - Else
          -> MAINTAIN GOLD & DIA WT.
    """
    cat = str(article_desc or "").upper()

    if "MANGALSUTRA" in cat:
        return 'MAINTAIN GOLD & DIA WT, FISH LOCK WITH MANGALSUTRA CHAIN NEED SMALL "O"KADI'
    if "EAR" in cat:
        return "MAINTAIN GOLD & DIA WT, POST IN CENTER."
    return "MAINTAIN GOLD & DIA WT."

# 🔁 DUPLICATION FUNCTION FOR BANGLES
def _expand_bangle_rows(df):
    """
    Duplicate rows if SKU/Style has 'BG' and PCS/OrderQty > 1.
    """
    expanded = []
    for _, row in df.iterrows():
        sku = str(row.get("SKUNo", "")).upper()
        style = str(row.get("StyleCode", "")).upper()
        pcs = int(row.get("OrderQty", 1))
        if ("BG" in sku or "BG" in style) and pcs > 1:
            for _ in range(pcs):
                expanded.append(row.copy())
        else:
            expanded.append(row.copy())
    return pd.DataFrame(expanded)

def _format_item_po(item_po_val, order_sl_val):
    """
    Build ItemPoNo as:
        '{ORDER SL NUMBER}-{TARGETED SHOPS}'
    If ORDER SL NUMBER is blank, just TARGETED SHOPS.
    """
    base = "" if pd.isna(item_po_val) else str(item_po_val).strip()
    if not base:
        return ""

    if pd.isna(order_sl_val):
        prefix = ""
    else:
        try:
            prefix = str(int(float(order_sl_val)))
        except Exception:
            prefix = str(order_sl_val).strip()

    return f"{prefix}-{base}" if prefix else base

def _style_suffix(s: str) -> str:
    """
    Extract trailing digits from StyleCode for set grouping.
    XNEC3225   -> '3225'
    JW-PEB0719 -> '0719'
    """
    m = re.search(r"(\d+)$", str(s))
    return m.group(1) if m else ""

